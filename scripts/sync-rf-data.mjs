// Generates src/integration/rfData.ts from a checkout of the RF Frequency Manager (RF-Scan-Editor).
// Usage: node scripts/sync-rf-data.mjs ../rf-scan-editor
// Takes over the product list (56b-products.js), the band list (50-bands-data.js) and the series types
// (56-equipment.js) so both programs use the same ids: product "Shure|AD4D", band/profile "Shure|ULX-D|G50".
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';

const repo = path.resolve(process.argv[2] || '../rf-scan-editor');
const js = (f) => fs.readFileSync(path.join(repo, 'src/js', f), 'utf8');

/** cut `const NAME = [ … ];` / `{ … };` out of a source file and evaluate the literal */
function literal(src, name, open) {
  const start = src.indexOf(`const ${name} = ${open}`);
  if (start < 0) throw new Error(`${name} not found`);
  const close = open === '[' ? ']' : '}';
  let depth = 0, i = src.indexOf(open, start);
  for (; i < src.length; i++) {
    const ch = src[i];
    if (ch === "'" || ch === '"' || ch === '`') { const q = ch; i++; while (src[i] !== q) { if (src[i] === '\\') i++; i++; } continue; }
    if (ch === '/' && src[i + 1] === '/') { while (src[i] !== '\n') i++; continue; }
    if (ch === open) depth++;
    else if (ch === close && --depth === 0) break;
  }
  return Function(`return ${src.slice(src.indexOf(open, start), i + 1)}`)();
}

const bands = literal(js('50-bands-data.js'), 'BAND_DATA', '[');
const products = literal(js('56b-products.js'), 'PRODUCTS', '[');
const series = literal(js('56-equipment.js'), 'EQUIP_SERIES', '{');
let commit = '';
try { commit = execSync('git rev-parse --short HEAD', { cwd: repo }).toString().trim(); } catch { /* not a git checkout */ }
const version = JSON.parse(fs.readFileSync(path.join(repo, 'package.json'), 'utf8')).version;

const out = `// GENERATED by scripts/sync-rf-data.mjs from RF Frequency Manager v${version}${commit ? ` (${commit})` : ''} – do not edit by hand.
// Band ranges there are "compiled from general knowledge – verify against the manufacturer".

/** [manufacturer, model, series, channels per unit (0 = free), max channels when free] */
export const RF_PRODUCTS_RAW: [string, string, string, number, number?][] = ${JSON.stringify(products.map((p) => [p[0], p[1], p[2], p[3] || 0, ...(p[4] ? [p[4]] : [])]))};

/** [manufacturer, series, band, [[from, to] MHz …]] */
export const RF_BANDS_RAW: [string, string, string, number[][]][] = ${JSON.stringify(bands.map((b) => [b[0], b[1], b[2], b[3]]))};

/** "manufacturer|series" → type: mic / iem / wmas / auto (self-coordinating, not coordinated) */
export const RF_SERIES_TYPE: Record<string, string> = ${JSON.stringify(Object.fromEntries(Object.entries(series).map(([k, v]) => [k, v.type])))};

export const RF_SOURCE_VERSION = ${JSON.stringify(version + (commit ? ` (${commit})` : ''))};
`;
const target = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../src/integration/rfData.ts');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
console.log(`wrote ${target}: ${products.length} products, ${bands.length} bands, ${Object.keys(series).length} series`);
